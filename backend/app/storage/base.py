"""Private object storage abstraction.

Keys are generated by the application only (never from user input) and validated
against a strict pattern before any backend touches them. Objects are private: there is
no public URL; the API streams them after an authorization or signature check.

Implementations: LocalFileStorage (development, tests, single-host demo). A future
S3-compatible backend implements the same protocol (see docs, "Production storage").
"""

import re
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

KEY_PATTERN = re.compile(
    r"^[a-z0-9][a-z0-9-]*(/[a-z0-9][a-z0-9-]*)*\.(webp|png|jpg|pdf|docx|txt|md|html|csv)$"
)


class StorageError(Exception):
    """Backend unavailable or write/read failed. Message is safe to log, not to show."""


class InvalidKeyError(ValueError):
    pass


def check_key(key: str) -> str:
    if len(key) > 160 or not KEY_PATTERN.fullmatch(key) or ".." in key:
        raise InvalidKeyError("invalid storage key")
    return key


@dataclass(frozen=True)
class StoredObject:
    key: str
    size: int
    modified_at: datetime


class Storage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...  # idempotent
    def list(self, prefix: str) -> list[StoredObject]: ...
