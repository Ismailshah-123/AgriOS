"""Build the E2 validation comparison table from SAVED files only (no recomputation).

python scripts/compare_val.py reports/E2_efficientnet_b0_tomato_v1/val reports/E2_mobilenet_v3_large_tomato_v1/val \
    --runs runs/E2_efficientnet_b0_tomato_v1/seed42 runs/E2_mobilenet_v3_large_tomato_v1/seed42 \
    --out reports/E2_VALIDATION_COMPARISON.md

Refuses any metrics.json with final_evaluation=true: model selection must use validation only.
"""

import argparse
import json
from pathlib import Path


def load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("reports", nargs="+", type=Path)
    ap.add_argument("--runs", nargs="+", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    rows, per_class = [], {}
    for rep, run in zip(a.reports, a.runs, strict=True):
        m = load(rep / "metrics.json")
        if m.get("final_evaluation"):
            raise SystemExit(f"{rep}: contains test results; this table is validation-only")
        s = load(run / "train_summary.json")
        hist = load(run / "history.json")
        v, vc, mod = m["val"], m["val_calibrated"], m["model"]
        cpu = (mod.get("latency_cpu_bs1") or {}).get("p50_ms")
        gpu = (mod.get("latency_gpu_bs1") or {}).get("p50_ms")
        train_s = sum(h.get("epoch_seconds", 0) for h in hist)
        rows.append(
            f"| {m['exp_id']} | {m['arch']} | {m['best_epoch']} | {len(hist)} | {v['accuracy']:.4f} | "
            f"{v['macro_f1']:.4f} | {vc['macro_f1']:.4f} | {v['ece_15']:.4f} -> {vc['ece_15']:.4f} | "
            f"{v['brier']:.4f} -> {vc['brier']:.4f} | {m['temperature']:.3f} | {mod['params']:,} | "
            f"{mod['checkpoint_bytes'] / 1e6:.1f} | {cpu if cpu is None else f'{cpu:.1f}'} | "
            f"{gpu if gpu is None else f'{gpu:.1f}'} | {train_s / 60:.0f} | {s.get('train_images')} / {s.get('val_images')} |"
        )
        per_class[m["exp_id"]] = v["per_class"]
    names = list(per_class)
    classes = list(per_class[names[0]])
    pc = ["| class | " + " | ".join(f"{n} P / R" for n in names) + " |", "|---|" + "---|" * len(names)]
    for c in classes:
        cells = [f"{per_class[n][c]['precision']:.3f} / {per_class[n][c]['recall']:.3f}" for n in names]
        pc.append(f"| {c} | " + " | ".join(cells) + " |")
    text = "\n".join([
        "# E2 validation comparison (generated by ml/scripts/compare_val.py from saved files)",
        "VALIDATION ONLY. Internal test and external (PlantDoc/PlantWild) sets were not opened. "
        "Calibrated values use a temperature fitted on this same validation set (in-sample; "
        "E5 must report calibration on test). Latency = p50 batch-1 forward on this PC.",
        "",
        "| exp | arch | best epoch | epochs run | val acc | val macro-F1 | val macro-F1 (T) | ECE15 raw -> T | Brier raw -> T | T | params | ckpt MB | CPU ms | GPU ms | train min | train / val imgs |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        "## Per-class validation precision / recall",
        *pc,
        "",
        "Selection is NOT made here: write ml/reports/SELECTION.md with the rule in "
        "docs/06-ai-ml-research/POST_TRAINING_RUNBOOK.md before any test access.",
    ])  # fmt: skip
    a.out.write_text(text + "\n", encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
